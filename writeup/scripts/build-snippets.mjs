// Copies the code shown on each card out of the repo's Python files into snippets.js, so the write-up never drifts
// from the source. Run after editing a .py file or a card's line ranges:
//   node writeup/scripts/build-snippets.mjs           rewrite snippets.js
//   node writeup/scripts/build-snippets.mjs --check   exit 1 if snippets.js is stale
import {readFile,writeFile} from 'node:fs/promises';
import {dirname,join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {steps} from '../content.js';
const writeup=join(dirname(fileURLToPath(import.meta.url)),'..');
const repo=join(writeup,'..');
const sources={};
const snippets={};
for(const step of steps){
 const card=step.card;
 if(card.type!=='code')continue;
 sources[card.file]??=(await readFile(join(repo,card.file),'utf8')).split('\n');
 const source=sources[card.file];
 const lines=[];
 card.ranges.forEach(([from,to],i)=>{
  if(from<1||to>source.length||from>to)throw new Error(`${step.id}: ${card.file} has no lines ${from}–${to}`);
  if(i>0)lines.push(null);
  for(let n=from;n<=to;n++)lines.push([n,source[n-1].trimEnd()]);
 });
 for(const n of card.focus)if(!lines.some(line=>line&&line[0]===n))throw new Error(`${step.id}: focus line ${n} is outside its ranges`);
 snippets[step.id]=lines;
}
const output=`// Generated by scripts/build-snippets.mjs from the repo's Python files. Do not edit by hand.\n// Each line is [line number, text]; null marks lines left out between ranges.\nexport const snippets = {\n${Object.entries(snippets).map(([id,lines])=>` ${JSON.stringify(id)}: [\n${lines.map(line=>`  ${JSON.stringify(line)}`).join(',\n')}\n ]`).join(',\n')}\n};\n`;
const target=join(writeup,'snippets.js');
if(process.argv.includes('--check')){
 const current=await readFile(target,'utf8').catch(()=>'');
 if(current!==output){console.error('snippets.js is stale: run node writeup/scripts/build-snippets.mjs');process.exit(1);}
 console.log('snippets.js is up to date');
} else {
 await writeFile(target,output);
 console.log(`snippets.js: ${Object.keys(snippets).length} snippets`);
}
