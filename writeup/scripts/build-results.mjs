// Writes the Results tab's data from a training run: results/model.bin (every weight and bias as little-endian
// float32, layer by layer: weights row-major, then biases) and results/run.js (the loss at every iteration and a few
// numbers about the run). Run after training, or on a checkpoint mid-run:
//   node writeup/scripts/build-results.mjs                     model.json + train_log.txt, every logged iteration
//   node writeup/scripts/build-results.mjs --iterations 6000   cut the log at the checkpoint model.json holds
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import {dirname,join,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {argmax,forward,unpack} from '../infer.js';
const writeup=join(dirname(fileURLToPath(import.meta.url)),'..');
const repo=join(writeup,'..');
const flag=name=>{const i=process.argv.indexOf(name);return i<0?undefined:process.argv[i+1];};

const model=JSON.parse(await readFile(resolve(repo,flag('--model')??'model.json'),'utf8'));
const shapes=model.layers.map(({w,b})=>{
 if(w.some(row=>row.length!==b.length))throw new Error('every weight row needs one value per bias');
 return [w.length,b.length];
});
const floats=new Float32Array(shapes.reduce((n,[rows,cols])=>n+rows*cols+cols,0));
let k=0;
for(const {w,b} of model.layers){for(const row of w)for(const v of row)floats[k++]=v;for(const v of b)floats[k++]=v;}

// same line format plot_loss.py reads; a repeated iteration keeps its last line
const log=await readFile(resolve(repo,flag('--log')??'train_log.txt'),'utf8');
const rows=new Map();
for(const m of log.matchAll(/iter (\d+): loss ([0-9.]+(?:e[-+]?\d+)?)\s+\(([0-9.]+)s since last iter\)/g))rows.set(+m[1],[+m[2],+m[3]]);
const iterations=+(flag('--iterations')??rows.size);
const losses=[];
let seconds=0;
for(let i=0;i<iterations;i++){
 if(!rows.has(i))throw new Error(`the log has no iteration ${i}`);
 const [loss,dt]=rows.get(i);
 losses.push(Math.round(loss*1e4)/1e4);
 seconds+=dt;
}

// scored with the float32 weights and infer.js, i.e. exactly what the page runs
const dataset=JSON.parse(await readFile(join(repo,'dataset.json'),'utf8'));
const layers=unpack(floats,shapes);
const correct=dataset.filter(({x,y})=>argmax(forward(layers,x))===y).length;

const last=losses.slice(-200);
const run={
 iterations,
 seconds:Math.round(seconds),
 layers:shapes,
 parameters:floats.length,
 samples:dataset.length,
 correct,
 last200:Math.round(last.reduce((s,v)=>s+v,0)/last.length*1e4)/1e4,
 losses
};
await mkdir(join(writeup,'results'),{recursive:true});
await writeFile(join(writeup,'results','model.bin'),Buffer.from(floats.buffer));
await writeFile(join(writeup,'results','run.js'),`// Generated by scripts/build-results.mjs from model.json and train_log.txt. Do not edit by hand.\nexport const run = ${JSON.stringify(run)};\n`);
console.log(`results: ${floats.length} parameters, ${iterations} iterations (${(seconds/3600).toFixed(2)} h), last-200 mean loss ${run.last200}, ${correct}/${dataset.length} correct`);
