"""Runs one real kuangrad step and writes the numbers the graph shows to writeup/pass.js.

    python3 writeup/scripts/build_pass.py

Fresh weights, initialised like forward_and_backward.py with random.seed(24), on sample 210 (the drawn 2 on the
digits card). Uses the engine itself: multi / relu / sftmx / inverse_log_max build the graph, and the same BFS walk
fills every grad (without the parameter update, so the weights shown are the ones the gradients were taken at).
"""
import json
import os
import sys
from collections import deque
from math import sqrt
from random import seed, uniform

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
sys.path.insert(0, REPO)
from draw_dataset import load_dataset  # noqa: E402
from neuron import Neuron  # noqa: E402
from operations import multi, relu, sftmx, inverse_log_max  # noqa: E402

SAMPLE = 210
# the rows of each layer the graph draws; None is the "…" between them
SLOTS = {
    "x": [0, 1, None, 7, 8, None, 255],
    "z1": [0, 1, 2, 3, None, 511], "a1": [0, 1, 2, 3, None, 511],
    "z2": [0, 1, 2, None, 254, 255], "a2": [0, 1, 2, None, 254, 255],
    "l": [0, 1, 2, None, 8, 9], "p": [0, 1, 2, None, 8, 9],
    "L": [0],
}
ORDER = ["x", "z1", "a1", "z2", "a2", "l", "p", "L"]


def init_neuron(fan_in):
    bound = 1 / sqrt(fan_in)
    return Neuron(value=round(uniform(-bound, bound), 5))


seed(24)  # shows a representative mix of alive and dead units in the rows the graph draws
w1, b1 = [], [init_neuron(256) for _ in range(512)]
for _ in range(256):
    w1.append([init_neuron(256) for _ in range(512)])
w2, b2 = [], [init_neuron(512) for _ in range(256)]
for _ in range(512):
    w2.append([init_neuron(512) for _ in range(256)])
w3, b3 = [], [init_neuron(256) for _ in range(10)]
for _ in range(256):
    w3.append([init_neuron(256) for _ in range(10)])

sample = load_dataset()[SAMPLE]
x = [Neuron(value=v) for v in sample["x"]]
z1 = multi(x, w1, b1)
a1 = relu(z1)
z2 = multi(a1, w2, b2)
a2 = relu(z2)
l = multi(a2, w3, b3)
p = sftmx(l)
loss = inverse_log_max(probs=p, label=sample["y"])

loss.grad = 1.0
queue, seen = deque([loss]), {loss}
while queue:
    node = queue.popleft()
    for parent in node.parents:
        parent.grad += parent.local_grad_to(node) * node.grad
        if parent not in seen:
            seen.add(parent)
            queue.append(parent)

layers = {"x": x, "z1": z1, "a1": a1, "z2": z2, "a2": a2, "l": l, "p": p, "L": [loss]}
shown = {k: [s for s in v if s is not None] for k, v in SLOTS.items()}
r = lambda v: float(f"{v:.6g}")

# one path the animation follows: the inked pixel x7 up to the loss, through units that are alive
featured = {"x": 7, "l": sample["y"], "p": sample["y"], "L": 0}
for z, a in (("z1", "a1"), ("z2", "a2")):
    alive = [s for s in shown[z] if layers[z][s].value > 0]
    featured[z] = featured[a] = max(alive, key=lambda s: layers[z][s].value)

matrices = {}
for name, w, src, dst in (("w1", w1, "x", "z1"), ("w2", w2, "a1", "z2"), ("w3", w3, "a2", "l")):
    matrices[name] = {
        "w": [[r(w[i][j].value) for j in shown[dst]] for i in shown[src]],
        "grad": [[r(w[i][j].grad) for j in shown[dst]] for i in shown[src]],
    }

# per link: the cached derivative along the featured edge (forward), and the featured parent's grad as a sum over
# its children (backward): the shown children one by one, the rest as one number
links = []
for c in range(len(ORDER) - 1):
    parent = layers[ORDER[c]][featured[ORDER[c]]]
    child_name = ORDER[c + 1]
    child = layers[child_name][featured[child_name]]
    terms = [[s, r(parent.local_grad_to(layers[child_name][s])), r(layers[child_name][s].grad)]
             for s in shown[child_name] if any(e[0] is layers[child_name][s] for e in parent.local_grads)]
    rest = parent.grad - sum(parent.local_grad_to(layers[child_name][s]) * layers[child_name][s].grad for s, _, _ in terms)
    links.append({
        "local": r(parent.local_grad_to(child)),
        "terms": terms,
        "rest": {"count": len(parent.local_grads) - len(terms), "sum": r(rest)},
        "total": r(parent.grad),
    })

out = {
    "sample": SAMPLE,
    "label": sample["y"],
    "slots": SLOTS,
    "values": {k: [r(layers[k][s].value) for s in shown[k]] for k in ORDER},
    "grads": {k: [r(layers[k][s].grad) for s in shown[k]] for k in ORDER},
    "matrices": matrices,
    "featured": featured,
    "links": links,
    "edge": {"x": r(x[7].value), "w": r(w1[7][3].value)},
}
target = os.path.join(REPO, "writeup", "pass.js")
with open(target, "w") as f:
    f.write("// Generated by scripts/build_pass.py from one real kuangrad step. Do not edit by hand.\n")
    f.write(f"export const pass = {json.dumps(out, separators=(',', ':'))};\n")
print(f"pass.js: sample {SAMPLE} (label {sample['y']}), loss {loss.value:.4f}, featured {featured}")
